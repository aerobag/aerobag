import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const nexradSchemaPath = path.join(repoRoot, "ui/core-rust/schemas/nexrad-overlay-wire.schema.json");
const cloudSchemaPath = path.join(repoRoot, "ui/core-rust/schemas/cloud-wire.schema.json");
const homePageSchemaPath = path.join(repoRoot, "ui/core-rust/schemas/home-page-wire.schema.json");
const sessionPageSchemaPath = path.join(repoRoot, "ui/core-rust/schemas/session-page-wire.schema.json");
const sessionUpdateSchemaPath = path.join(repoRoot, "ui/core-rust/schemas/session-update-wire.schema.json");
const sessionUpdateConformancePath = path.join(
  repoRoot,
  "ui/core-rust/crates/app-ui-contracts/tests/goldens/session-update-conformance.json",
);

const args = new Map();
const flags = new Set();
for (let index = 2; index < process.argv.length; index += 1) {
  const arg = process.argv[index];
  if (arg.startsWith("--") && process.argv[index + 1] && !process.argv[index + 1].startsWith("--")) {
    args.set(arg, process.argv[index + 1]);
    index += 1;
  } else {
    flags.add(arg);
  }
}

const webOut =
  args.get("--web-out") ?? path.join(repoRoot, "ui/web-app/src/generated/nexradOverlayWire.ts");
const androidOut =
  args.get("--android-out") ??
  path.join(
    repoRoot,
    "ui/android-app/app/build/generated/aerobagWire/kotlin/org/aerobag/app/generated",
  );
const checkOnly = flags.has("--check");
const cloudWebOut =
  args.get("--cloud-web-out") ?? path.join(repoRoot, "ui/web-app/src/generated/cloudWire.ts");
const homePageWebOut =
  args.get("--home-page-web-out") ?? path.join(repoRoot, "ui/web-app/src/generated/homePageWire.ts");
const sessionPageWebOut =
  args.get("--session-page-web-out") ?? path.join(repoRoot, "ui/web-app/src/generated/sessionPageWire.ts");
const sessionUpdateWebOut =
  args.get("--session-update-web-out") ?? path.join(repoRoot, "ui/web-app/src/generated/sessionUpdateWire.ts");
const sessionUpdateConformanceWebOut =
  args.get("--session-update-conformance-web-out")
    ?? path.join(repoRoot, "ui/web-app/src/generated/sessionUpdateConformance.json");

let schemaPath;
let schema;
let defs;
let exportOrder;
let generatedBanner;

function loadSchema(nextSchemaPath) {
  schemaPath = nextSchemaPath;
  schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
  defs = {
    ...schema.$defs,
    [schema.title]: schema,
  };
  exportOrder = schema["x-export-order"] ?? Object.keys(defs);
  // REUSE-IgnoreStart
  generatedBanner =
    "// SPDX-FileCopyrightText: 2026 Aerobag contributors\n" +
    "// SPDX-License-Identifier: AGPL-3.0-or-later\n\n" +
    `// @generated by tools/generate-ui-wire-types.mjs from ${path.relative(repoRoot, schemaPath)}\n`;
  // REUSE-IgnoreEnd
}

function resolveRef(ref) {
  const prefix = "#/$defs/";
  if (!ref?.startsWith(prefix)) {
    throw new Error(`unsupported schema ref ${ref}`);
  }
  const name = ref.slice(prefix.length);
  const resolved = defs[name];
  if (!resolved) {
    throw new Error(`unknown schema ref ${ref}`);
  }
  return { name, schema: resolved };
}

function baseSchema(fieldSchema) {
  if (Array.isArray(fieldSchema.anyOf)) {
    const nonNull = fieldSchema.anyOf.filter((entry) => entry.type !== "null");
    if (nonNull.length === 1 && nonNull.length !== fieldSchema.anyOf.length) {
      return nonNull[0];
    }
  }
  if (fieldSchema.$ref) {
    return fieldSchema;
  }
  if (Array.isArray(fieldSchema.type)) {
    return {
      ...fieldSchema,
      type: fieldSchema.type.filter((type) => type !== "null")[0],
    };
  }
  return fieldSchema;
}

function isNullable(fieldSchema) {
  return (Array.isArray(fieldSchema.type) && fieldSchema.type.includes("null"))
    || (Array.isArray(fieldSchema.anyOf) && fieldSchema.anyOf.some((entry) => entry.type === "null"));
}

function snakeToCamel(name) {
  return name.replaceAll(/_([a-z])/g, (_, letter) => letter.toUpperCase());
}

function enumMemberName(value) {
  return value
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function contractVersionName() {
  const screaming = schema.title.replaceAll(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
  return `${screaming}_WIRE_VERSION`;
}

function sessionUpdateGroupProperties() {
  if (schema.title !== "UiSessionUpdate") return [];
  return Object.entries(schema.properties ?? {}).filter(([, propertySchema]) => {
    const schemaBase = baseSchema(propertySchema);
    return schemaBase.$ref && resolveRef(schemaBase.$ref).name === "UiSessionProjectionPatch";
  });
}

function ktSessionUpdateGroupSource() {
  const groups = sessionUpdateGroupProperties();
  if (groups.length === 0) return "";
  const members = groups.map(([wireName]) =>
    `    ${enumMemberName(wireName)}(${JSON.stringify(wireName)}),`
  );
  const patches = groups.map(([wireName]) => {
    const propertyName = snakeToCamel(wireName);
    return `    ${propertyName}?.let { add(UiSessionUpdateGroup.${enumMemberName(wireName)} to it) }`;
  });
  return `\nenum class UiSessionUpdateGroup(val wireName: String) {\n${members.join("\n")}\n}\n\nfun UiSessionUpdate.projectionPatches(): List<Pair<UiSessionUpdateGroup, UiSessionProjectionPatch>> =\n  buildList {\n${patches.join("\n")}\n  }\n`;
}

function tsSessionUpdateGroupSource() {
  const groups = sessionUpdateGroupProperties();
  if (groups.length === 0) return "";
  const wireNames = groups.map(([wireName]) => JSON.stringify(wireName)).join(", ");
  return `\nexport const UI_SESSION_UPDATE_GROUPS = [${wireNames}] as const;\n\nexport type UiSessionUpdateGroup = typeof UI_SESSION_UPDATE_GROUPS[number];\n`;
}

function ktDefault(fieldSchema, ktType) {
  if (Object.hasOwn(fieldSchema, "default")) {
    const value = fieldSchema.default;
    if (value === null) return " = null";
    if (Array.isArray(value)) return " = emptyList()";
    if (typeof value === "object") return ` = ${ktType}()`;
    if (typeof value === "string") {
      if (defs[ktType]?.enum?.includes(value)) {
        return ` = ${ktType}.${enumMemberName(value)}`;
      }
      return ` = ${JSON.stringify(value)}`;
    }
    if (typeof value === "number") return ` = ${ktType === "Double" ? value.toFixed(1) : value}`;
    if (typeof value === "boolean") return ` = ${value}`;
  }
  if (isNullable(fieldSchema)) return " = null";
  return "";
}

function ktType(fieldSchema) {
  if (fieldSchema === true || (typeof fieldSchema === "object" && Object.keys(fieldSchema).length === 0)) {
    return "JsonElement";
  }
  const schemaBase = baseSchema(fieldSchema);
  if (schemaBase.$ref) {
    const type = resolveRef(schemaBase.$ref).name;
    return isNullable(fieldSchema) ? `${type}?` : type;
  }
  const nullable = isNullable(fieldSchema);
  let type;
  switch (schemaBase.type) {
    case "array":
      type = `List<${ktType(schemaBase.items)}>`;
      break;
    case "integer":
      type = schemaBase.format?.endsWith("64") ? "Long" : "Int";
      break;
    case "number":
      type = "Double";
      break;
    case "string":
      type = "String";
      break;
    case "boolean":
      type = "Boolean";
      break;
    case "object":
      if (schemaBase.additionalProperties === true || typeof schemaBase.additionalProperties === "object") {
        type = "JsonObject";
        break;
      }
      throw new Error("inline object schemas need a named $defs entry");
    default:
      throw new Error(`unsupported Kotlin schema type ${schemaBase.type}`);
  }
  return nullable ? `${type}?` : type;
}

function tsType(fieldSchema) {
  if (fieldSchema === true || (typeof fieldSchema === "object" && Object.keys(fieldSchema).length === 0)) {
    return "unknown";
  }
  if (Object.hasOwn(fieldSchema, "const")) {
    return JSON.stringify(fieldSchema.const);
  }
  const schemaBase = baseSchema(fieldSchema);
  if (schemaBase.$ref) {
    const type = resolveRef(schemaBase.$ref).name;
    return isNullable(fieldSchema) ? `${type} | null` : type;
  }
  const nullable = isNullable(fieldSchema);
  if (fieldSchema.oneOf) {
    return fieldSchema.oneOf.map(tsInlineObjectType).join(" | ");
  }
  let type;
  switch (schemaBase.type) {
    case "array":
      type = `${tsType(schemaBase.items)}[]`;
      break;
    case "integer":
    case "number":
      type = "number";
      break;
    case "string":
      type = "string";
      break;
    case "boolean":
      type = "boolean";
      break;
    case "object":
      if (schemaBase.additionalProperties === true || typeof schemaBase.additionalProperties === "object") {
        type = "Record<string, unknown>";
        break;
      }
      throw new Error("inline object schemas need a named $defs entry");
    default:
      throw new Error(`unsupported TypeScript schema type ${schemaBase.type}`);
  }
  return nullable ? `${type} | null` : type;
}

function tsInlineObjectType(objectSchema) {
  const required = new Set(objectSchema.required ?? []);
  const fields = Object.entries(objectSchema.properties ?? {}).map(([wireName, propertySchema]) => {
    const optional = required.has(wireName) || Object.hasOwn(propertySchema, "default") ? "" : "?";
    return `${wireName}${optional}: ${tsType(propertySchema)}`;
  });
  return `{ ${fields.join("; ")} }`;
}

function ktObjectSource(name, objectSchema) {
  const required = new Set(objectSchema.required ?? []);
  const properties = Object.entries(objectSchema.properties ?? {});
  if (properties.length === 0) {
    return `@Serializable\nclass ${name}\n`;
  }
  const fields = properties.map(([wireName, propertySchema]) => {
    const propertyName = snakeToCamel(wireName);
    const baseType = ktType(propertySchema);
    const hasDefault = Object.hasOwn(propertySchema, "default");
    const type = required.has(wireName) || hasDefault || baseType.endsWith("?") ? baseType : `${baseType}?`;
    const serialName = propertyName === wireName ? "" : `    @SerialName("${wireName}")\n`;
    const defaultValue = required.has(wireName) ? ktDefault(propertySchema, type) : ktDefault(propertySchema, type) || " = null";
    return `${serialName}    val ${propertyName}: ${type}${defaultValue}`;
  });
  return `@Serializable\ndata class ${name}(\n${fields.join(",\n")},\n)\n`;
}

function ktEnumSource(name, enumSchema) {
  return `@Serializable\nenum class ${name} {\n${enumSchema.enum
    .map((value) => `    @SerialName("${value}")\n    ${enumMemberName(value)},`)
    .join("\n")}\n}\n`;
}

function tsObjectSource(name, objectSchema) {
  const required = new Set(objectSchema.required ?? []);
  const properties = Object.entries(objectSchema.properties ?? {});
  const fields = properties.map(([wireName, propertySchema]) => {
    const optional = required.has(wireName) || Object.hasOwn(propertySchema, "default") ? "" : "?";
    return `  ${wireName}${optional}: ${tsType(propertySchema)};`;
  });
  return `export type ${name} = {\n${fields.join("\n")}\n};\n`;
}

function tsEnumSource(name, enumSchema) {
  return `export type ${name} = ${enumSchema.enum.map((value) => JSON.stringify(value)).join(" | ")};\n`;
}

function taggedUnionInfo(unionSchema) {
  const discriminator = unionSchema["x-discriminator"];
  if (!discriminator) {
    throw new Error("oneOf schemas require x-discriminator");
  }
  const variants = unionSchema.oneOf.map((variant) => {
    const tag = variant.properties?.[discriminator]?.const;
    if (typeof tag !== "string") {
      throw new Error(`tagged union variants require a ${discriminator} const`);
    }
    return { tag, title: variant.title ?? enumMemberName(tag), schema: variant };
  });
  return { discriminator, variants };
}

function ktTaggedUnionSource(name, unionSchema) {
  const { discriminator, variants } = taggedUnionInfo(unionSchema);
  const members = variants.map(({ tag, title, schema: variant }) => {
    const required = new Set(variant.required ?? []);
    const fields = Object.entries(variant.properties ?? {})
      .filter(([wireName]) => wireName !== discriminator)
      .map(([wireName, propertySchema]) => {
        const propertyName = snakeToCamel(wireName);
        const baseType = ktType(propertySchema);
        const type = required.has(wireName) || baseType.endsWith("?") ? baseType : `${baseType}?`;
        const serialName = propertyName === wireName ? "" : `        @SerialName("${wireName}")\n`;
        const defaultValue = required.has(wireName)
          ? ktDefault(propertySchema, type)
          : ktDefault(propertySchema, type) || " = null";
        return `${serialName}        val ${propertyName}: ${type}${defaultValue}`;
      });
    if (fields.length === 0) {
      return `    @Serializable\n    @SerialName("${tag}")\n    data object ${title} : ${name}`;
    }
    return `    @Serializable\n    @SerialName("${tag}")\n    data class ${title}(\n${fields.join(",\n")},\n    ) : ${name}`;
  });
  return `@OptIn(ExperimentalSerializationApi::class)\n@Serializable\n@JsonClassDiscriminator("${discriminator}")\nsealed interface ${name} {\n${members.join("\n\n")}\n}\n`;
}

function tsTaggedUnionSource(name, unionSchema) {
  return `export type ${name} = ${unionSchema.oneOf.map(tsInlineObjectType).join(" | ")};\n`;
}

function androidSource() {
  const chunks = [];
  for (const name of exportOrder) {
    const entry = defs[name];
    if (!entry) throw new Error(`x-export-order refers to missing schema ${name}`);
    if (entry.enum) {
      chunks.push(ktEnumSource(name, entry));
    } else if (entry.oneOf) {
      chunks.push(ktTaggedUnionSource(name, entry));
    } else if (entry.type === "object") {
      chunks.push(ktObjectSource(name, entry));
    } else {
      throw new Error(`unsupported top-level Kotlin schema for ${name}`);
    }
  }
  const version = schema["x-contract-version"];
  const versionSource = Number.isInteger(version) ? `const val ${contractVersionName()}: Int = ${version}\n\n` : "";
  return `${generatedBanner}package org.aerobag.app.generated\n\nimport kotlinx.serialization.ExperimentalSerializationApi\nimport kotlinx.serialization.SerialName\nimport kotlinx.serialization.Serializable\nimport kotlinx.serialization.json.JsonClassDiscriminator\nimport kotlinx.serialization.json.JsonElement\nimport kotlinx.serialization.json.JsonObject\n\n${versionSource}${chunks.join("\n")}${ktSessionUpdateGroupSource()}`;
}

function webSource() {
  const chunks = [];
  for (const name of exportOrder) {
    const entry = defs[name];
    if (!entry) throw new Error(`x-export-order refers to missing schema ${name}`);
    if (entry.enum) {
      chunks.push(tsEnumSource(name, entry));
    } else if (entry.oneOf) {
      chunks.push(tsTaggedUnionSource(name, entry));
    } else if (entry.type === "object") {
      chunks.push(tsObjectSource(name, entry));
    } else {
      throw new Error(`unsupported top-level TypeScript schema for ${name}`);
    }
  }
  const version = schema["x-contract-version"];
  const versionSource = Number.isInteger(version) ? `export const ${contractVersionName()} = ${version} as const;\n\n` : "";
  return `${generatedBanner}\n${versionSource}${chunks.join("\n")}${tsSessionUpdateGroupSource()}`;
}

function writeOrCheck(filePath, content) {
  if (checkOnly) {
    const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : null;
    if (existing !== content) {
      console.error(`generated wire type output is stale: ${path.relative(repoRoot, filePath)}`);
      process.exitCode = 1;
    }
    return;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
}

loadSchema(nexradSchemaPath);
writeOrCheck(path.join(androidOut, "NexradOverlayWire.kt"), androidSource());
writeOrCheck(webOut, webSource());

loadSchema(cloudSchemaPath);
writeOrCheck(path.join(androidOut, "CloudWire.kt"), androidSource());
writeOrCheck(cloudWebOut, webSource());

loadSchema(homePageSchemaPath);
writeOrCheck(path.join(androidOut, "HomePageWire.kt"), androidSource());
writeOrCheck(homePageWebOut, webSource());

loadSchema(sessionPageSchemaPath);
writeOrCheck(path.join(androidOut, "SessionPageWire.kt"), androidSource());
writeOrCheck(sessionPageWebOut, webSource());

loadSchema(sessionUpdateSchemaPath);
writeOrCheck(path.join(androidOut, "SessionUpdateWire.kt"), androidSource());
writeOrCheck(sessionUpdateWebOut, webSource());
writeOrCheck(
  sessionUpdateConformanceWebOut,
  fs.readFileSync(sessionUpdateConformancePath, "utf8"),
);
