#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.join(repoRoot, "ui/core-rust/schemas/nexrad-overlay-wire.schema.json");

const args = new Map();
const flags = new Set();
for (let index = 2; index < process.argv.length; index += 1) {
  const arg = process.argv[index];
  if (arg.startsWith("--") && process.argv[index + 1] && !process.argv[index + 1].startsWith("--")) {
    args.set(arg, process.argv[index + 1]);
    index += 1;
  } else {
    flags.add(arg);
  }
}

const webOut =
  args.get("--web-out") ?? path.join(repoRoot, "ui/web-app/src/generated/nexradOverlayWire.ts");
const androidOut =
  args.get("--android-out") ??
  path.join(
    repoRoot,
    "ui/android-app/app/build/generated/aerobagWire/kotlin/org/aerobag/app/generated",
  );
const checkOnly = flags.has("--check");

const schema = JSON.parse(fs.readFileSync(schemaPath, "utf8"));
const defs = {
  ...schema.$defs,
  [schema.title]: schema,
};
const exportOrder = schema["x-export-order"] ?? Object.keys(defs);
const generatedBanner =
  "// @generated by tools/generate-ui-wire-types.mjs from ui/core-rust/schemas/nexrad-overlay-wire.schema.json\n";

function resolveRef(ref) {
  const prefix = "#/$defs/";
  if (!ref?.startsWith(prefix)) {
    throw new Error(`unsupported schema ref ${ref}`);
  }
  const name = ref.slice(prefix.length);
  const resolved = defs[name];
  if (!resolved) {
    throw new Error(`unknown schema ref ${ref}`);
  }
  return { name, schema: resolved };
}

function baseSchema(fieldSchema) {
  if (fieldSchema.$ref) {
    return fieldSchema;
  }
  if (Array.isArray(fieldSchema.type)) {
    return {
      ...fieldSchema,
      type: fieldSchema.type.filter((type) => type !== "null")[0],
    };
  }
  return fieldSchema;
}

function isNullable(fieldSchema) {
  return Array.isArray(fieldSchema.type) && fieldSchema.type.includes("null");
}

function snakeToCamel(name) {
  return name.replaceAll(/_([a-z])/g, (_, letter) => letter.toUpperCase());
}

function enumMemberName(value) {
  return value
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function ktDefault(fieldSchema, ktType) {
  if (Object.hasOwn(fieldSchema, "default")) {
    const value = fieldSchema.default;
    if (value === null) return " = null";
    if (Array.isArray(value)) return " = emptyList()";
    if (typeof value === "object") return ` = ${ktType}()`;
    if (typeof value === "string") return ` = ${JSON.stringify(value)}`;
    if (typeof value === "number") return ` = ${ktType === "Double" ? value.toFixed(1) : value}`;
    if (typeof value === "boolean") return ` = ${value}`;
  }
  if (isNullable(fieldSchema)) return " = null";
  return "";
}

function ktType(fieldSchema) {
  if (fieldSchema.$ref) {
    return resolveRef(fieldSchema.$ref).name;
  }
  const schemaBase = baseSchema(fieldSchema);
  const nullable = isNullable(fieldSchema);
  let type;
  switch (schemaBase.type) {
    case "array":
      type = `List<${ktType(schemaBase.items)}>`;
      break;
    case "integer":
      type = "Int";
      break;
    case "number":
      type = "Double";
      break;
    case "string":
      type = "String";
      break;
    case "object":
      throw new Error("inline object schemas need a named $defs entry");
    default:
      throw new Error(`unsupported Kotlin schema type ${schemaBase.type}`);
  }
  return nullable ? `${type}?` : type;
}

function tsType(fieldSchema) {
  if (fieldSchema.$ref) {
    return resolveRef(fieldSchema.$ref).name;
  }
  const schemaBase = baseSchema(fieldSchema);
  const nullable = isNullable(fieldSchema);
  let type;
  switch (schemaBase.type) {
    case "array":
      type = `${tsType(schemaBase.items)}[]`;
      break;
    case "integer":
    case "number":
      type = "number";
      break;
    case "string":
      type = "string";
      break;
    case "object":
      throw new Error("inline object schemas need a named $defs entry");
    default:
      throw new Error(`unsupported TypeScript schema type ${schemaBase.type}`);
  }
  return nullable ? `${type} | null` : type;
}

function ktObjectSource(name, objectSchema) {
  const required = new Set(objectSchema.required ?? []);
  const properties = Object.entries(objectSchema.properties ?? {});
  const fields = properties.map(([wireName, propertySchema]) => {
    const propertyName = snakeToCamel(wireName);
    const type = ktType(propertySchema);
    const serialName = propertyName === wireName ? "" : `    @SerialName("${wireName}")\n`;
    const defaultValue = required.has(wireName) ? ktDefault(propertySchema, type) : ktDefault(propertySchema, type) || " = null";
    return `${serialName}    val ${propertyName}: ${type}${defaultValue}`;
  });
  return `@Serializable\ndata class ${name}(\n${fields.join(",\n")},\n)\n`;
}

function ktEnumSource(name, enumSchema) {
  return `@Serializable\nenum class ${name} {\n${enumSchema.enum
    .map((value) => `    @SerialName("${value}")\n    ${enumMemberName(value)},`)
    .join("\n")}\n}\n`;
}

function tsObjectSource(name, objectSchema) {
  const required = new Set(objectSchema.required ?? []);
  const properties = Object.entries(objectSchema.properties ?? {});
  const fields = properties.map(([wireName, propertySchema]) => {
    const optional = required.has(wireName) ? "" : "?";
    return `  ${wireName}${optional}: ${tsType(propertySchema)};`;
  });
  return `export type ${name} = {\n${fields.join("\n")}\n};\n`;
}

function tsEnumSource(name, enumSchema) {
  return `export type ${name} = ${enumSchema.enum.map((value) => JSON.stringify(value)).join(" | ")};\n`;
}

function androidSource() {
  const chunks = [];
  for (const name of exportOrder) {
    const entry = defs[name];
    if (!entry) throw new Error(`x-export-order refers to missing schema ${name}`);
    if (entry.enum) {
      chunks.push(ktEnumSource(name, entry));
    } else if (entry.type === "object") {
      chunks.push(ktObjectSource(name, entry));
    } else {
      throw new Error(`unsupported top-level Kotlin schema for ${name}`);
    }
  }
  return `${generatedBanner}package org.aerobag.app.generated\n\nimport kotlinx.serialization.SerialName\nimport kotlinx.serialization.Serializable\n\n${chunks.join("\n")}`;
}

function webSource() {
  const chunks = [];
  for (const name of exportOrder) {
    const entry = defs[name];
    if (!entry) throw new Error(`x-export-order refers to missing schema ${name}`);
    if (entry.enum) {
      chunks.push(tsEnumSource(name, entry));
    } else if (entry.type === "object") {
      chunks.push(tsObjectSource(name, entry));
    } else {
      throw new Error(`unsupported top-level TypeScript schema for ${name}`);
    }
  }
  return `${generatedBanner}\n${chunks.join("\n")}`;
}

function writeOrCheck(filePath, content) {
  if (checkOnly) {
    const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, "utf8") : null;
    if (existing !== content) {
      console.error(`generated wire type output is stale: ${path.relative(repoRoot, filePath)}`);
      process.exitCode = 1;
    }
    return;
  }
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content);
}

writeOrCheck(path.join(androidOut, "NexradOverlayWire.kt"), androidSource());
writeOrCheck(webOut, webSource());
